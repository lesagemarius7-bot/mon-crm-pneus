/** Converts a field label ("Numéro de flotte") into a stable JSON key
 * ("numero_de_flotte") for CustomFieldDefinition.key. */
export function slugify(input: string): string {
  return input
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
}
